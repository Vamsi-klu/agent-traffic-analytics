"""Fetches the sources of the lists and writes a snapshot. This is the only part of Agent Cake that goes online,
and only when a release is built (tools/build_lists.py) or someone runs `agentcake lists update`; never while cake
runs.

    build(sources, kinds, fetch, previous, now) -> {file name: JSON object, or a licence file's text}   (fetch is
                                                   injected, so tests stay offline)
    update(fetch=None, now=None, root=None)     -> the folder written, <CAKE_HOME>/lists/<date>/
    write_files(files, folder)                  -> rewrites the generated files in a folder (the release's own)
    licence_file(source)                        -> the name of a repository's licence file beside the lists

Repositories are read at the commit their branch points to, which is recorded, after checking that their licence file
still says what sources.json expects. That licence file, unchanged, is written beside the lists as
<source>.LICENSE.txt: the sources are MIT, which asks for the copyright and permission notice in every copy, and the
notice is the one of the commit the lists come from. Any source that cannot be fetched or read stops the build with
BuildError and nothing is written, so the lists in use stay as they were.
"""
import datetime
import json
import os
import shutil
import tempfile
import urllib.error
import urllib.request
from collections import namedtuple

from agentcake.detect import lists, lists_keys, lists_names, lists_ranges

SCHEMA = 1
GENERATED = "Generated by tools/build_lists.py or `agentcake lists update` from sources.json: do not edit by hand."
LICENCE_FILE = "{source}.LICENSE.txt"  # as agentcake/static/src/<name>.LICENSE.txt sits beside the page code it covers
Response = namedtuple("Response", "status headers body")


class BuildError(Exception):
    """A source could not be fetched or read; nothing was written."""


def http_fetch(settings):
    """fetch(url, accept=None) -> Response, over HTTPS with the limits of sources.json "fetch"."""
    def fetch(url, accept=None):
        headers = {"User-Agent": settings["user_agent"], **({"Accept": accept} if accept else {})}
        attempts = []
        for _ in range(settings["retries"] + 1):
            try:
                with urllib.request.urlopen(urllib.request.Request(url, headers=headers),
                                            timeout=settings["timeout_s"]) as answer:
                    body = answer.read(settings["max_bytes"] + 1)
                    if len(body) > settings["max_bytes"]:
                        raise BuildError(f"{url}: larger than {settings['max_bytes']} bytes")
                    return Response(answer.status, {k.lower(): v for k, v in answer.headers.items()}, body)
            except (urllib.error.URLError, OSError, ValueError) as error:
                attempts.append(str(error))
        raise BuildError(f"{url}: {attempts[-1]}")
    return fetch


def read_recipe():
    with open(lists.SOURCES_FILE, encoding="utf-8") as f:
        sources = json.load(f)
    with open(lists.KINDS_FILE, encoding="utf-8") as f:
        kinds = json.load(f)["kinds"]
    return sources, kinds


def licence_file(source):
    return LICENCE_FILE.format(source=source)


def fetch_repo(fetch, github, spec):
    """A repository's files at the commit its branch points to now, and its licence file's text, after checking it."""
    for path in spec["files"].values():
        if spec.get("not_under") and path.startswith(spec["not_under"]):
            raise BuildError(f"{spec['repo']}: {path} is under {spec['not_under']}, which has another licence")
    head = json.loads(fetch(github["commit_api"].format(repo=spec["repo"], ref=spec["ref"])).body)
    commit = head["sha"]

    def raw(path):
        return fetch(github["raw"].format(repo=spec["repo"], commit=commit, path=path)).body.decode("utf-8")

    licence = raw(spec["license_file"])
    if spec["license_marker"] not in licence:
        raise BuildError(f"{spec['repo']}: {spec['license_file']} no longer says {spec['license_marker']!r}")
    files = {key: raw(path) for key, path in spec["files"].items()}
    about = {"repo": spec["repo"], "commit": commit, "committed": head["commit"]["committer"]["date"],
             "license": spec["license"], "url": github["tree"].format(repo=spec["repo"], commit=commit)}
    return about, files, licence


def _previous_keys(previous, botscent_keys):
    """Keys and fetch times of the snapshot in use, or botscent's own when there is none yet (the first build)."""
    if previous is not None:
        fetched = {}
        for host in previous.signer_hosts():
            when = (previous.directory_response(host) or {}).get("fetched_at")
            if when:
                fetched[host] = datetime.datetime.fromisoformat(when).timestamp()
        return previous.key_directories(), fetched
    data = json.loads(botscent_keys)
    when = datetime.datetime.fromisoformat(data["fetched_at"]).timestamp()
    return data["directories"], {host: when for host in data["directories"]}


def build(sources, kinds, fetch, previous, now):
    """Every generated file of a snapshot, built from what fetch() returns now. previous: the Lists in use, or None."""
    built, at = now.date().isoformat(), now.isoformat(timespec="seconds")
    repos, files, licences = {}, {}, {}
    try:
        for name, spec in sources["repos"].items():
            repos[name], files[name], licences[licence_file(name)] = fetch_repo(fetch, sources["github"], spec)
        names, hints, platforms, counts, disagreements = lists_names.build_names(
            sources["names"], kinds, files, sources["matching"]["regex_guard"])
        ranges = lists_ranges.build_ranges(sources["ip_ranges"], fetch)
        signers, directories, responses = lists_keys.build_signers(
            sources["signers"], json.loads(files["botscent"]["signers"])["signers"], fetch,
            _previous_keys(previous, files["botscent"]["keys"]), now)
    except (KeyError, TypeError, ValueError) as error:
        raise BuildError(f"reading the sources failed: {error!r}") from error
    about = {name: {**repos.get(name, {}), **count} for name, count in counts.items()}
    head = {"$comment": GENERATED, "schema": SCHEMA, "built": built, "built_at": at}
    matching = {k: sources["matching"][k] for k in ("token_before", "token_after")}
    return {
        "names.json": {**head, "sources": about, "matching": matching, "names": names, "hints": hints,
                       "platforms": platforms, "disagreements": disagreements},
        "ip_ranges.json": {**head, "ranges": ranges},
        "signers.json": {**head, "signers": signers},
        "keys.json": {**head, "fetched_at": at, "directories": directories, "responses": responses},
        **licences,
    }


def _dump(data, path):
    """A generated list as JSON, or a licence file's text exactly as it was fetched."""
    with open(path, "w", encoding="utf-8", newline="") as f:
        if isinstance(data, str):
            f.write(data)
            return
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write("\n")


def write_files(files, folder):
    """Rewrite the generated files of the release's own folder: all are written aside first, then each is swapped
    in, so a file that cannot be written leaves every file as it was."""
    staged = {name: os.path.join(folder, f".{name}.incoming") for name in files}
    try:
        for name, data in files.items():
            _dump(data, staged[name])
    except (OSError, TypeError, ValueError):
        for path in staged.values():
            if os.path.exists(path):
                os.remove(path)
        raise
    for name, path in staged.items():
        os.replace(path, os.path.join(folder, name))


def write_snapshot(files, root):
    """A new dated folder under root holding every file, swapped in whole: a reader sees the old or the new."""
    os.makedirs(root, exist_ok=True)
    target = os.path.join(root, files["names.json"]["built"])
    staging = tempfile.mkdtemp(prefix=".incoming-", dir=root)
    try:
        for name, data in files.items():
            _dump(data, os.path.join(staging, name))
        if os.path.isdir(target):
            retired = tempfile.mkdtemp(prefix=".retired-", dir=root)
            os.replace(target, os.path.join(retired, "old"))
            os.replace(staging, target)
            shutil.rmtree(retired)
        else:
            os.replace(staging, target)
    except OSError:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return target


def update(fetch=None, now=None, root=None):
    """`agentcake lists update`: fetch everything into <root>/<date>/, or raise BuildError and change nothing."""
    sources, kinds = read_recipe()
    root = root or lists.user_root()
    previous = lists.Lists.load(lists.BUNDLED_DIR, root)
    files = build(sources, kinds, fetch or http_fetch(sources["fetch"]), previous,
                  now or datetime.datetime.now(datetime.timezone.utc))
    folder = write_snapshot(files, root)
    lists.reload()
    return folder
