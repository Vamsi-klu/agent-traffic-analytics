#!/usr/bin/env python3
"""Build agentcake/data/timezones.json, which time zone each country uses, from the IANA time zone database.

    python3 -I tools/build_timezones.py [zone.tab]      (default: /usr/share/zoneinfo/zone.tab)

The weak signal "time zone and IP country do not match" (agentcake/detect/weak.py) reads it. Source: the tz
database's zone.tab, one line per country and zone (country code, coordinates, zone name, comments), public domain
(https://www.iana.org/time-zones). The tzdata version is read from +VERSION next to zone.tab when there is one. The
output is sorted, so the same zone.tab gives the same bytes. Run it when a release refreshes its lists.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "agentcake", "data", "timezones.json")
DEFAULT_SOURCE = "/usr/share/zoneinfo/zone.tab"
COLUMNS = 3  # zone.tab: country code, coordinates, zone name (then optional comments)


def read_zone_tab(path):
    """{zone name: [country codes]} from zone.tab."""
    zones = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            fields = line.rstrip("\n").split("\t")
            if len(fields) < COLUMNS:
                continue
            country, zone = fields[0], fields[COLUMNS - 1]
            zones.setdefault(zone, [])
            if country not in zones[zone]:
                zones[zone].append(country)
    return {zone: sorted(countries) for zone, countries in sorted(zones.items())}


def tzdata_version(path):
    version_file = os.path.join(os.path.dirname(path), "+VERSION")
    try:
        with open(version_file, encoding="utf-8") as f:
            return f.read().strip() or None
    except OSError:
        return None


def main(argv):
    source = argv[1] if len(argv) > 1 else DEFAULT_SOURCE
    zones = read_zone_tab(source)
    data = {"$comment": "Generated by tools/build_timezones.py from the IANA tz database's zone.tab (public domain): "
                        "the countries that use each time zone. Do not edit by hand.",
            "tzdata": tzdata_version(source), "zones": zones}
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1, sort_keys=True)
        f.write("\n")
    print(f"{len(zones)} time zones written to {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
